class DashboardRequestHandler(BaseHTTPRequestHandler):
    logs_dir: Path = DEFAULT_LOGS_DIR

    def do_GET(self) -> None:
        if self.path == "/" or self.path.startswith("/?"):
            # Instant response: only read already-generated charts
            with chart_lock:
                overview = self.logs_dir / "multi_seed_overview.png"
                seed_charts = sorted(self.logs_dir.glob("seed_*_progress_chart.png"))
                ordered_charts: List[Path] = []
                if overview.exists():
                    ordered_charts.append(overview)
                ordered_charts.extend(seed_charts)
                html = build_html_page(ordered_charts)

            content = html.encode("utf-8")
            self.send_response(HTTPStatus.OK)
            self.send_header("Content-Type", "text/html; charset=utf-8")
            self.send_header("Content-Length", str(len(content)))
            self.send_header("Cache-Control", "no-cache, no-store, must-revalidate")
            self.end_headers()
            self.wfile.write(content)
            return

        if self.path.startswith("/image/"):
            img_name = self.path.split("/image/")[1].split("?")[0]
            img_path = self.logs_dir / img_name
            if img_path.exists() and img_path.is_file() and img_path.suffix.lower() == ".png":
                mime, _ = mimetypes.guess_type(str(img_path))
                with chart_lock:
                    raw_bytes = img_path.read_bytes()
                self.send_response(HTTPStatus.OK)
                self.send_header("Content-Type", mime or "image/png")
                self.send_header("Content-Length", str(len(raw_bytes)))
                self.send_header("Cache-Control", "no-cache, no-store, must-revalidate")
                self.end_headers()
                self.wfile.write(raw_bytes)
                return
            else:
                self.send_error(HTTPStatus.NOT_FOUND, "Image not found")
                return

        self.send_error(HTTPStatus.NOT_FOUND, "Not Found")

    def log_message(self, format: str, *args) -> None:
        # Standard compact logging
        print(f"[{datetime.now().strftime('%H:%M:%S')}] {args[0]} - {args[1]}", flush=True)


def main() -> None:
    parser = argparse.ArgumentParser(description="Live Training Charts Webserver (Periodic Background Generation)")
    parser.add_argument("--port", "-p", type=int, default=8080, help="Port to listen on (default: 8080)")
    parser.add_argument("--host", type=str, default="0.0.0.0", help="Host address (default: 0.0.0.0)")
    parser.add_argument(
        "--dir", "-d", type=str, default=str(DEFAULT_LOGS_DIR), help="Directory containing progress.jsonl logs"
    )
    parser.add_argument(
        "--interval", "-i", type=int, default=300, help="Chart regeneration interval in seconds (default: 300)"
    )
    args = parser.parse_args()

    global generation_interval_sec
    generation_interval_sec = args.interval

    logs_path = Path(args.dir)
    logs_path.mkdir(parents=True, exist_ok=True)
    DashboardRequestHandler.logs_dir = logs_path

    # Start periodic background generator thread
    worker = threading.Thread(
        target=periodic_generator_worker,
        args=(logs_path, args.interval),
        daemon=True,
    )
    worker.start()

    server = ThreadingHTTPServer((args.host, args.port), DashboardRequestHandler)
    print("=" * 75, flush=True)
    print(f"🚀 BRL-GMCTS Chart Dashboard running on http://localhost:{args.port}", flush=True)
    print(f"⏱️  Background chart generation timer: every {args.interval}s (5 minutes)", flush=True)
    print(f"⚡ Page serving: Instant (serves cached PNGs without regeneration delay)", flush=True)
    print(f"📂 Monitoring directory: {logs_path.resolve()}", flush=True)
    print("=" * 75, flush=True)

    try:
        server.serve_forever()
    except KeyboardInterrupt:
        print("\nShutting down server...", flush=True)
        server.server_close()


if __name__ == "__main__":
    main()
