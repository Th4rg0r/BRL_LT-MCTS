ROOT_DIR = Path(__file__).resolve().parent
DEFAULT_LOGS_DIR = ROOT_DIR / "outputs" / "fast_validation" / "logs"
PLOT_SCRIPT = ROOT_DIR / "experiments" / "plot_progress.py"

# Thread-safe generation state
chart_lock = threading.Lock()
last_generation_time_str = "Never"
last_generation_duration = 0.0
next_generation_timestamp = 0.0
generation_interval_sec = 300  # 5 minutes


def run_chart_generation(logs_dir: Path) -> None:
    """Executes experiments/plot_progress.py in a thread-safe manner."""
    global last_generation_time_str, last_generation_duration, next_generation_timestamp
    with chart_lock:
        t0 = time.time()
        print(f"[{datetime.now().strftime('%H:%M:%S')}] [BackgroundWorker] Regenerating charts...", flush=True)
        cmd = [
            sys.executable,
            str(PLOT_SCRIPT),
            "--dir",
            str(logs_dir),
        ]
        res = subprocess.run(cmd, cwd=str(ROOT_DIR), capture_output=True, text=True)
        duration = time.time() - t0
        if res.returncode != 0:
            print(f"[BackgroundWorker Error] plot_progress failed:\n{res.stderr}", flush=True)
        else:
            print(f"[{datetime.now().strftime('%H:%M:%S')}] [BackgroundWorker] Charts updated in {duration:.2f}s", flush=True)

        last_generation_time_str = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
        last_generation_duration = duration
        next_generation_timestamp = time.time() + generation_interval_sec


def periodic_generator_worker(logs_dir: Path, interval: int) -> None:
    """Daemon thread that periodically runs chart generation every `interval` seconds."""
    # Run once immediately at startup
    run_chart_generation(logs_dir)

    while True:
        time.sleep(1)
        if time.time() >= next_generation_timestamp:
            run_chart_generation(logs_dir)


